// GreenHive.NET.WorkflowContracts
// Contracts for workflows, shared by the client, the backend services and modules (net10.0, no UI).
// Three capabilities: define workflows over several input interactions inside a module, show which workflows
// are affected by a module update (impact analysis), and let AI run workflows based on triggers under policies.
// Contents: WorkflowDefinition, WorkflowStep, InputSchema, WorkflowTransition, WorkflowTrigger, WorkflowInstance,
// WorkflowDependency, WorkflowImpactReport, AiExecutionPolicy, IWorkflowStepHandler, WorkflowExpression.
